import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# define variables
L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

# create x values
x = np.linspace(0, L, 500) # creates 500 evenly spaced points along the 6-foot beam

# create an array for shear values
V = np.zeros_like(x) # creates an array of zeros to store shear values - AI help

# calculate shear at each x value
for i in range(len(x)): # checks each position and applies the appropriate shear equation
    if x[i] < 2:
        V[i] = RA - q1 * x[i]
    elif x[i] < 4:
        V[i] = RA - q1 * 2 - P1
    else:
        V[i] = RA - q1 * 2 - P1 + RB - q2 * (x[i] - 4)

# plot the shear diagram
plt.figure(figsize=(8, 5))
plt.plot(x, V) # draws the line
plt.fill_between(x, V, 0, alpha=0.35) # shades the area between the line and zero - AI help
plt.axhline(0, color='black', linewidth=1)
plt.title("Shear Diagram")
plt.xlabel("x (ft)")
plt.ylabel("V (lb)")
plt.show()

