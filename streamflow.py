"""### Part 2 - Pasadena Precipitation Data

You will now create a graph using Pasadena Temperature Data from 2013-2014.

### Numpy Array Creation & Slicing

Create and slice the array to create the x and y-axis values. These will correspond to the following columns in the CSV linked on readthedocs:

*   x - Date
*   y_1 - High Temperature
*   y_2 - Low Temperature
"""

# load pasadena temp data
data = np.genfromtxt( # np.genfromtxt() reads information from a CSV file and stores it in a NumPy array called data
    '2013-2014-Pasadena-Temperature-Data.csv',
    delimiter=',', # columns are separated by commas
    dtype=str, # read all values as text (strings)
    skip_header=1 # skip the first row of column titles
)

# slice the array into columns
x = data[:, 0] # selects the first column, which contains the dates
y_1 = data[:, 1].astype(float) # select the second column (contains high temps), astype(float) converts text values into decimal numbers
y_2 = data[:, 2].astype(float) # select the third column (contains low temps)

"""### Graphing the Data

Plot x, y_1 and y_2 with the elements shown in the instructions on the HW page.
"""

import matplotlib.dates as mdates
import datetime as dt

# convert dates into datetime objects
dates = [dt.datetime.strptime(d, '%Y-%m-%d') for d in x] # strptime() converts each string into a datetime object so matplotlib to recognize dates instead of text

# create graph
plt.figure(figsize=(8, 5)) # creates figure with dimensions 8in wide and 5in tall

plt.plot(dates, y_1, label='High Temperature') # plots the high temperatures against the dates,  label assigns a name to this line for the legend
plt.plot(dates, y_2, label='Low Temperature') # plots the low temperatures against the dates

plt.title('Pasadena Temperature Data 2013-2014') # add a descriptive title above the graph
plt.xlabel('Date') # label the horizontal axis (x-axis)
plt.ylabel('Degrees (Fahrenheit)') # label the vertical axis (y-axis)


plt.gca().xaxis.set_major_locator(mdates.MonthLocator(interval=2)) # get the current axes and control how dates are displayed, monthlocator places a tick ever two months
plt.gca().xaxis.set_major_formatter(mdates.DateFormatter('%Y-%m')) # dateformatter displays dates as year-month (2013-06)

plt.legend() # display a legend identifying the two temperature lines
plt.grid(True) # add gridlines to make the values easier to compare

plt.tight_layout() # automatically adjust spacing to prevent overlapping text
plt.show() # display the completed graph

